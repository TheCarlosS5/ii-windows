"""Generates what depends on shared/actions.json (U01/U02) and checks it.

    python gen-actions.py                      write the generated files
    python gen-actions.py --check              fail if a generated file differs from what would be written
    python gen-actions.py --check --consumers <staged ii dir>
                                               also fail if a 'shell' target has no GlobalShortcut of that
                                               name in the QML (an action that swallows a key and does nothing)

Generated: host/src/shortcuts_table.inc, overlay/ii/services/HyprlandKeybinds.qml, docs/ATAJOS.md.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SOURCE = os.path.join(ROOT, 'shared', 'actions.json')
OUT_TABLE = os.path.join(ROOT, 'host', 'src', 'shortcuts_table.inc')
OUT_QML = os.path.join(ROOT, 'overlay', 'ii', 'services', 'HyprlandKeybinds.qml')
OUT_DOC = os.path.join(ROOT, 'docs', 'ATAJOS.md')

VK = {
    'Tab': 'VK_TAB', 'Period': 'VK_OEM_PERIOD', 'Slash': 'VK_OEM_2', 'End': 'VK_END', 'Print': 'VK_SNAPSHOT',
    'F4': 'VK_F4', 'Escape': 'VK_ESCAPE', 'Delete': 'VK_DELETE', 'Up': 'VK_UP',
}
MASK = {'shift': 'shift', 'ctrl': 'ctrl', 'alt': 'alt', 'win': 'superKey'}
STATES = ('available', 'partial', 'external', 'unsupported')
SWALLOWING_KINDS = ('shell', 'host')


def load():
    data = json.load(open(SOURCE, encoding='utf-8'))
    if data.get('schema') != 1:
        sys.exit('shared/actions.json: unknown schema')
    return data


def vk_expr(key):
    if key in VK:
        return VK[key]
    if re.fullmatch(r'[A-Z0-9]', key):
        return f"'{key}'"
    return None


def swallowing(action):
    """(key entry) pairs this action makes the host swallow."""
    if action['target']['kind'] not in SWALLOWING_KINDS:
        return []
    return [k for k in action['keys'] if k.get('swallow', True)]


def validate(data):
    ids = set()
    combos = {}
    for action in data['actions']:
        aid = action['id']
        if aid in ids:
            sys.exit(f'duplicate id {aid}')
        ids.add(aid)
        if action['support'] not in STATES:
            sys.exit(f'{aid}: unknown support {action["support"]}')
        if action['support'] in ('partial', 'external', 'unsupported') and not action.get('reason'):
            sys.exit(f'{aid}: support {action["support"]} needs a reason (never a silent limit)')
        if 'kind' not in action['target']:
            sys.exit(f'{aid}: target needs a kind')
        for k in swallowing(action):
            if vk_expr(k['key']) is None:
                sys.exit(f'{aid}: no virtual-key mapping for {k["key"]}')
            combo = (tuple(sorted(k['mods'])), k['key'])
            if combo in combos:
                sys.exit(f'{aid}: {combo} is already taken by {combos[combo]}')
            combos[combo] = aid
    return data


def table(data):
    lines = ['// GENERATED by tools/dev/gen-actions.py from shared/actions.json: do not edit.',
             '// {win, ctrl, alt, shift, virtual key, name}: the name is a shell GlobalShortcut, or "@..." for ii-host itself.']
    for action in data['actions']:
        for k in swallowing(action):
            m = k['mods']
            flags = ', '.join('true' if x in m else 'false' for x in ('win', 'ctrl', 'alt', 'shift'))
            lines.append(f'Shortcut {{{flags}, {vk_expr(k["key"])}, L"{action["target"]["name"]}"}}, // {action["id"]}')
    return '\n'.join(lines) + '\n'


def qml(data):
    out = ['pragma Singleton', 'pragma ComponentBehavior: Bound', '',
           '// GENERATED by tools/dev/gen-actions.py from shared/actions.json: do not edit.',
           "// The shortcuts ii-host actually maps (and the Windows ones that stay as they are), in the shape of",
           '// `hyprctl binds -j` for the cheatsheet.', '',
           'import QtQuick', 'import Quickshell', '', 'Singleton {', '    id: root', '',
           '    // Hyprland modmask bits',
           '    readonly property int shift: 1 << 0', '    readonly property int ctrl: 1 << 2',
           '    readonly property int alt: 1 << 3', '    readonly property int superKey: 1 << 6', '',
           '    function bind(modmask, key, description) {',
           '        return { "modmask": modmask, "key": key, "description": description };', '    }', '',
           '    property var keybinds: [']
    for action in data['actions']:
        if action.get('cheatsheet', True) is False:
            continue
        for k in action['keys']:
            mods = ' | '.join(MASK[x] for x in k['mods']) or '0'
            text = f'{action["group"]}: {action["text"]}'.replace('\\', '\\\\').replace('"', '\\"')
            out.append(f'        bind({mods}, "{k["key"]}", "{text}"),')
    out += ['    ]', '', '    property var keybindCategories: {', '        const groups = [];',
            '        for (const bind of keybinds) {',
            '            const group = bind.description.substring(0, bind.description.indexOf(":"));',
            '            if (group.length > 0 && !groups.includes(group)) groups.push(group);', '        }',
            '        return groups;', '    }', '}']
    return '\n'.join(out) + '\n'


def doc(data):
    names = {'win': 'Win', 'ctrl': 'Ctrl', 'alt': 'Alt', 'shift': 'Shift'}
    rows = ['| Atajo | Acción | Estado | Destino | Nota |', '| --- | --- | --- | --- | --- |']
    for action in data['actions']:
        for k in action['keys']:
            combo = '+'.join([names[m] for m in ('ctrl', 'alt', 'shift', 'win') if m in k['mods']] + [k['key']])
            if not k.get('swallow', True) or action['target']['kind'] not in SWALLOWING_KINDS:
                combo += ' (lo atiende Windows)' if action['target']['kind'] == 'windows' else ''
            target = action['target'].get('name', action['target']['kind'])
            rows.append(f'| {combo} | {action["text"]} | {action["support"]} | `{target}` | {action.get("reason", "")} |')
    head = ('# Atajos de teclado de ii-windows\n\n'
            'Generado con `python tools/dev/gen-actions.py` desde `shared/actions.json` (única fuente: la tabla que traga '
            '`ii-host`, la chuleta de la shell y este documento salen de ahí). **No editar a mano.**\n\n'
            'Estados: ' + '; '.join(f'**{k}** = {v}' for k, v in data['support'].items()) + '\n\n'
            'Los atajos de ii se resuelven dentro de ii también con una aplicación maximizada. Ceden el paso '
            '(y Windows recupera la tecla) solo cuando una aplicación está en pantalla completa exclusiva o a modo '
            'de juego; la regla se puede cambiar en `%LOCALAPPDATA%\\ii-windows\\shortcuts.ini` (ver `docs/DECISIONS.md`). '
            'Ctrl+Alt+Mayús+R (pánico) es una tecla de sistema de `ii-host` y funciona incluso con los atajos cedidos.\n\n')
    return head + '\n'.join(rows) + '\n'


def outputs(data):
    return {OUT_TABLE: table(data), OUT_QML: qml(data), OUT_DOC: doc(data)}


def check_consumers(data, staged):
    names = set()
    for base, _d, files in os.walk(staged):
        for f in files:
            if f.endswith('.qml'):
                text = open(os.path.join(base, f), encoding='utf-8', errors='replace').read()
                names.update(re.findall(r'GlobalShortcut\s*\{[^}]*?name:\s*"([^"]+)"', text, re.S))
    missing = []
    for action in data['actions']:
        if action['target']['kind'] == 'shell' and swallowing(action) and action['target']['name'] not in names:
            missing.append(f'{action["id"]} -> {action["target"]["name"]}')
    return missing


def main():
    args = sys.argv[1:]
    data = validate(load())
    wanted = outputs(data)
    if '--check' in args:
        bad = []
        for path, text in wanted.items():
            have = open(path, encoding='utf-8', newline='').read().replace('\r\n', '\n') if os.path.exists(path) else None
            if have != text:
                bad.append(os.path.relpath(path, ROOT))
        if bad:
            sys.exit('out of date (run tools/dev/gen-actions.py): ' + ', '.join(bad))
        if '--consumers' in args:
            missing = check_consumers(data, args[args.index('--consumers') + 1])
            if missing:
                sys.exit('shell targets nobody listens to: ' + ', '.join(missing))
        print('actions: generated files are current')
        return
    for path, text in wanted.items():
        open(path, 'w', encoding='utf-8', newline='').write(text)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
