"""Plan 2026-10-31, E16: the data of Configuración > Atajos, from the one list of ii's keyboard actions.

Runs in stage-ii.ps1. Reads shared/actions.json and writes modules/settings/shortcuts-data.js (.pragma library):
`var actions = [{id, group, text, support, reason, keys: [{mods, key}], editable}]`. `editable`: ii-host takes its
combination (a shell or host action it swallows), so shortcuts.ini [keys] can give it another one or none.
"""
import json
import os
import sys

ROOT = os.environ.get('II_STAGE_DIR') or os.path.join(os.path.dirname(__file__), '..', '..', 'build', 'ii')
SOURCE = os.path.join(os.path.dirname(__file__), '..', '..', 'shared', 'actions.json')
OUT = os.path.join(ROOT, 'modules', 'settings', 'shortcuts-data.js')

with open(SOURCE, encoding='utf-8') as f:
    data = json.load(f)
if data.get('schema') != 1:
    sys.exit('gen_shortcuts_data.py: unknown schema of shared/actions.json')

actions = []
for action in data['actions']:
    swallowed = [k for k in action['keys'] if k.get('swallow', True)]
    actions.append({
        'id': action['id'],
        'group': action['group'],
        'text': action['text'],
        'support': action['support'],
        'reason': action.get('reason', ''),
        'keys': [{'mods': k['mods'], 'key': k['key']} for k in action['keys']],
        'editable': action['target']['kind'] in ('shell', 'host') and len(swallowed) > 0,
    })

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('.pragma library\n// Generated by tools/port/gen_shortcuts_data.py from shared/actions.json (plan 2026-10-31, E16).\n')
    f.write('var actions = ' + json.dumps(actions, ensure_ascii=False, indent=1) + ';\n')
print(f'shortcuts data: {len(actions)} actions, {sum(a["editable"] for a in actions)} editable')
